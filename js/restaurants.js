const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

export const RESTAURANT_FOODS = RESTAURANTS.flatMap(r => r.items.map(([name, serving, kcal, protein, carbs, fat, src]) => ({
  id: `rs:${r.id}:${slug(name + '-' + serving)}`,
  name, serving: `${r.name}, ${serving}`, kcal, protein, carbs, fat,
  restaurant: r.id, official: src === 'us', source: 'restaurant',
  tags: `${r.name} ${r.tag} restaurant fast food`,
})));

export const restaurantById = id => RESTAURANTS.find(r => r.id === id);
export const foodsOf = id => RESTAURANT_FOODS.filter(f => f.restaurant === id);
